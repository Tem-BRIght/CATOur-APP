// QR-code scanner page. Recognizes TWO QR formats:
//   1. Tour-session QR (created by the guide) → joins the session.
//   2. Destination QR (created in the admin panel, /destination?id=<docId>)
//      → records a confirmed visit, fires the AI proximity guide as a
//        GPS-independent backup trigger, then opens the destination page.
// ─────────────────────────────────────────────────────────────────────────────

